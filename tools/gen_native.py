"""Generate the Rust host table for the native runtime.

The JSON spec holds the Rust expression an agent writes for each host step;
running the script writes src/generated_host.rs.  It is not a translator from
Viba source and it does not rewrite recursion: the generated table only
replaces the Python `get_func` boundary for the listed host steps.

    python3 tools/gen_native.py
    cargo build --release
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = json.loads((ROOT / "tools" / "native_spec.json").read_text())


def host_source() -> str:
    lines = [
        "// Generated by tools/gen_native.py. Do not edit.",
        "use crate::native_runtime::Value;",
        "",
        "fn int_arg(args: &[Value], index: usize) -> Result<i64, String> {",
        "    match args.get(index) {",
        "        Some(Value::Int(value)) => Ok(*value),",
        "        Some(_) => Err(format!(\"argument {index} is not an int\")),",
        "        None => Err(format!(\"argument {index} is missing\")),",
        "    }",
        "}",
        "",
        "pub(crate) fn call(module: &str, name: &str, args: &[Value]) -> Option<Result<Value, String>> {",
        "    match (module, name) {",
    ]
    for module, functions in SPEC["hosts"].items():
        for name, body in functions.items():
            lines.append(f'        ("{module}", "{name}") => {body},')
    lines += [
        "        _ => None,",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    (ROOT / "src" / "generated_host.rs").write_text(host_source())
    print("wrote src/generated_host.rs")


if __name__ == "__main__":
    main()
